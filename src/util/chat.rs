pub struct ChatComponent;

impl ChatComponent {
    pub fn text(message: &str) -> String {
        let colored = crate::limbo::texts::color_codes(message);
        format!("{{\"text\":\"{}\"}}", Self::escape(&colored))
    }

    fn escape(s: &str) -> String {
        let mut out = String::with_capacity(s.len() + 8);
        for c in s.chars() {
            match c {
                '"' => out.push_str("\\\""),
                '\\' => out.push_str("\\\\"),
                '\n' => out.push_str("\\n"),
                '\r' => out.push_str("\\r"),
                '\t' => out.push_str("\\t"),
                c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
                c => out.push(c),
            }
        }
        out
    }
}
