use once_cell::sync::Lazy;

pub fn map_palette_lut() -> &'static [u8] {
    static LUT: Lazy<Vec<u8>> = Lazy::new(|| {
        let bases: [[u8; 3]; 62] = [
            [0, 0, 0],
            [127, 178, 56],
            [247, 233, 163],
            [199, 199, 199],
            [255, 0, 0],
            [160, 160, 255],
            [167, 167, 167],
            [0, 124, 0],
            [255, 255, 255],
            [164, 168, 184],
            [151, 109, 77],
            [112, 112, 112],
            [64, 64, 255],
            [143, 119, 72],
            [255, 252, 245],
            [216, 127, 51],
            [178, 76, 216],
            [102, 153, 216],
            [229, 229, 51],
            [127, 204, 25],
            [242, 127, 165],
            [76, 76, 76],
            [153, 153, 153],
            [76, 127, 153],
            [127, 63, 178],
            [51, 76, 178],
            [102, 76, 51],
            [102, 127, 51],
            [153, 51, 51],
            [25, 25, 25],
            [250, 238, 77],
            [92, 219, 213],
            [74, 128, 255],
            [0, 217, 58],
            [129, 86, 49],
            [112, 2, 0],
            [209, 177, 161],
            [159, 82, 36],
            [149, 87, 108],
            [112, 108, 138],
            [186, 133, 36],
            [103, 117, 53],
            [160, 77, 78],
            [57, 41, 35],
            [135, 107, 98],
            [87, 92, 92],
            [122, 73, 88],
            [76, 62, 92],
            [76, 50, 35],
            [76, 82, 42],
            [142, 60, 46],
            [37, 22, 16],
            [189, 48, 49],
            [148, 63, 97],
            [92, 25, 29],
            [22, 126, 134],
            [58, 142, 140],
            [86, 44, 62],
            [20, 180, 133],
            [100, 100, 100],
            [216, 175, 147],
            [127, 167, 150],
        ];
        let shades = [0.71_f32, 0.86, 1.0, 0.53];
        let mut palette = Vec::with_capacity(62 * 4);
        for base in bases {
            for shade in shades {
                palette.push([
                    (f32::from(base[0]) * shade) as u8,
                    (f32::from(base[1]) * shade) as u8,
                    (f32::from(base[2]) * shade) as u8,
                ]);
            }
        }
        let mut lut = vec![0; 32 * 32 * 32];
        for r in 0..32 {
            for g in 0..32 {
                for b in 0..32 {
                    let target = [
                        ((r * 8 + 4).min(255)) as i32,
                        ((g * 8 + 4).min(255)) as i32,
                        ((b * 8 + 4).min(255)) as i32,
                    ];
                    let mut best = u32::MAX;
                    let mut best_id = 0;
                    for (id, color) in palette.iter().enumerate().skip(4) {
                        let dr = target[0] - i32::from(color[0]);
                        let dg = target[1] - i32::from(color[1]);
                        let db = target[2] - i32::from(color[2]);
                        let distance = (dr * dr + dg * dg + db * db) as u32;
                        if distance < best {
                            best = distance;
                            best_id = id as u8;
                        }
                    }
                    lut[(r << 10) | (g << 5) | b] = best_id;
                }
            }
        }
        lut
    });
    &LUT
}
