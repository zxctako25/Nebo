fn damage_type_entry(
    id: i32,
    name: &str,
    scaling: &str,
    exhaustion: f32,
    message_id: &str,
    effects: Option<&str>,
    death_message_type: Option<&str>,
) -> NbtTag {
    let mut element = vec![
        string("scaling", scaling),
        float("exhaustion", exhaustion),
        string("message_id", message_id),
    ];
    if let Some(effects) = effects {
        element.push(string("effects", effects));
    }
    if let Some(death_message_type) = death_message_type {
        element.push(string("death_message_type", death_message_type));
    }
    compound(vec![
        string("name", &format!("minecraft:{name}")),
        int("id", id),
        ("element".to_owned(), compound(element)),
    ])
}
